/**
 * Demo seed: creates a sample org + website + prompts + responses + metrics
 * so the app renders meaningful data without any external setup.
 * Run: npm run db:seed
 */
import "dotenv/config";
import { db } from "./index.js";
import {
  users,
  organizations,
  orgMembers,
  websites,
  topics,
  prompts,
  promptSchedules,
  competitors,
  runs,
  responses,
  responseMentions,
  responseCitations,
  sources,
  creditBalances,
  creditLedger,
  subscriptions,
} from "./index.js";
import { eq } from "drizzle-orm";

const MODELS = ["chatgpt", "perplexity", "gemini", "claude", "copilot", "grok", "ai_overview", "ai_mode"];

async function seed() {
  const email = process.env.SEED_EMAIL ?? "demo@example.com";
  let [user] = await db.select().from(users).where(eq(users.email, email));
  if (!user) [user] = await db.insert(users).values({ email, name: "Demo User" }).returning();

  let [org] = await db.select().from(organizations).where(eq(organizations.slug, "demo"));
  if (!org) [org] = await db.insert(organizations).values({ name: "Demo Org", slug: "demo" }).returning();

  await db.insert(orgMembers).values({ organizationId: org.id, userId: user.id, role: "owner" }).onConflictDoNothing();

  const [website] = await db
    .insert(websites)
    .values({
      organizationId: org.id,
      domain: "canvasly.io",
      name: "Canvasly",
      profile: {
        description: "AI-native design canvas for product teams",
        products: ["Design canvas", "Prototyping", "Design tokens"],
        audiences: ["Product designers", "Frontend engineers"],
        differentiators: ["AI-first", "Realtime collaboration"],
      },
    })
    .returning();

  const topicRows = await db
    .insert(topics)
    .values([
      { websiteId: website.id, name: "Brand Content Automation" },
      { websiteId: website.id, name: "Design Software Comparisons" },
      { websiteId: website.id, name: "Color Theory" },
    ])
    .returning();

  await db.insert(promptSchedules).values({ websiteId: website.id, name: "Default", kind: "default", cadence: "daily" });

  const promptTexts = [
    "best ai design tools for product teams",
    "how to create design tokens automatically",
    "figma vs canvasly for prototyping",
    "what are the best color theory resources",
    "ai tools for design system automation",
  ];
  const promptRows = await db
    .insert(prompts)
    .values(
      promptTexts.map((text, i) => ({
        websiteId: website.id,
        topicId: topicRows[i % topicRows.length].id,
        text,
        type: text.toLowerCase().includes("canvasly") ? ("branded" as const) : ("non_branded" as const),
      })),
    )
    .returning();

  const competitorRows = await db
    .insert(competitors)
    .values([
      { websiteId: website.id, domain: "figma.com", name: "Figma" },
      { websiteId: website.id, domain: "adobe.com", name: "Adobe Express" },
      { websiteId: website.id, domain: "canva.com", name: "Canva" },
    ])
    .returning();

  // 30 days of responses
  const [run] = await db
    .insert(runs)
    .values({ websiteId: website.id, state: "completed", totalResponses: promptRows.length * MODELS.length * 30, creditsReserved: promptRows.length * MODELS.length * 30, startedAt: new Date(), finishedAt: new Date() })
    .returning();

  const now = Date.now();
  const rows: (typeof responses.$inferInsert)[] = [];
  for (let day = 29; day >= 0; day--) {
    for (const p of promptRows) {
      for (const model of MODELS) {
        const mentioned = ((day + p.text.length + model.length) % 10) < 6;
        const cited = mentioned && ((day + model.length) % 3) === 0;
        rows.push({
          runId: run.id,
          promptId: p.id,
          websiteId: website.id,
          model,
          rawText: `Sample answer for "${p.text}" generated by ${model}. Canvasly is ${mentioned ? "recommended as a top choice for product teams." : "not mentioned in this answer."}`,
          mentioned,
          cited,
          position: mentioned ? 1 + ((day + model.length) % 5) : null,
          sentiment: mentioned ? (((day % 5) === 0 ? "positive" : "neutral") as const) : "unknown",
          ranAt: new Date(now - day * 86400_000),
        });
      }
    }
  }
  const inserted = await db.insert(responses).values(rows).returning({ id: responses.id, mentioned: responses.mentioned });

  const mentionRows: (typeof responseMentions.$inferInsert)[] = [];
  const citationRows: (typeof responseCitations.$inferInsert)[] = [];
  for (const r of inserted) {
    if (r.mentioned) {
      mentionRows.push({ responseId: r.id, name: "Canvasly", sentiment: "positive", position: 1 });
      for (const c of competitorRows) {
        if ((parseInt(r.id.slice(0, 4), 16) % 3) === 0) {
          mentionRows.push({ responseId: r.id, competitorId: c.id, name: c.name, sentiment: "neutral", position: 2 });
        }
      }
    }
    if (parseInt(r.id.slice(0, 4), 16) % 2 === 0) {
      const domain = ["youtube.com", "reddit.com", "medium.com", "linkedin.com", "canva.com"][parseInt(r.id.slice(0, 2), 16) % 5];
      citationRows.push({ responseId: r.id, url: `https://${domain}/article`, domain, rank: 1, isBrand: domain === "canvasly.io" });
    }
  }
  if (mentionRows.length) await db.insert(responseMentions).values(mentionRows);
  if (citationRows.length) await db.insert(responseCitations).values(citationRows);

  // Source aggregates
  await db.insert(sources).values(
    [
      { domain: "youtube.com", type: "c" as const, citationPct: 39.18, brandMentionPct: 37.28, influenced: 48800 },
      { domain: "reddit.com", type: "c" as const, citationPct: 21.24, brandMentionPct: 39.85, influenced: 26500 },
      { domain: "medium.com", type: "t" as const, citationPct: 17.44, brandMentionPct: 32.45, influenced: 21700 },
      { domain: "linkedin.com", type: "t" as const, citationPct: 16.04, brandMentionPct: 32.38, influenced: 20000 },
      { domain: "canva.com", type: "o" as const, citationPct: 15.67, brandMentionPct: 72.5, influenced: 19500 },
    ].map((s) => ({
      websiteId: website.id,
      domain: s.domain,
      type: s.type,
      citationCount: Math.round(s.citationPct * 100),
      mentionInfluenced: s.influenced,
      responsesInfluenced: s.influenced,
      competitorMentionPct: String(s.brandMentionPct),
      spark: Array.from({ length: 14 }, (_, i) => ({
        date: new Date(now - (13 - i) * 86400_000).toISOString().slice(0, 10),
        citationRate: s.citationPct * (0.9 + 0.2 * Math.random()),
      })),
    })),
  );

  await db.insert(creditBalances).values({ organizationId: org.id, balance: 2700 });
  await db.insert(creditLedger).values({ organizationId: org.id, kind: "grant", amount: 3000, reason: "Free plan monthly credits" });
  await db.insert(subscriptions).values({ organizationId: org.id, plan: "free", monthlyCredits: 3000 });

  console.log("Seed complete:", { org: org.slug, website: website.domain, responses: inserted.length });
}

seed()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error(err);
    process.exit(1);
  });
